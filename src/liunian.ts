// 流年纯函数（ADR-0003）
// "今年起向后 10 柱干支"，由独立纯函数产出。
// 不注入 排盘Input、不进 排盘Result；"今天"由 CLI 边缘按北京时间读机器时钟算出
// 今年公历年再传入。排盘核心保持无时钟、纯函数不变。
//
// 每柱 = 六十甲子((公历年 - 4) mod 60)（甲子=0，2000 -> 庚辰）。
// 不查立春时刻，纯按公历年 mod 60（CONTEXT.md 流年术语）。

import { liushijiazi } from "./ganzhi.js";

/** 流年柱：年（公历）+ 该年干支。 */
export interface 流年柱 {
  年: number;
  干支: string;
}

/** 流年输出长度：今年起向后 10 柱。 */
const 流年柱数 = 10;

/**
 * 流年纯函数：给定今年公历年，返回从今年起向后 10 柱干支。
 * 每柱 = 六十甲子((公历年 - 4) mod 60)，公历年每 +1，序号 +1。
 * 不查立春，纯按公历年 mod 60（CONTEXT.md）。
 *
 * 例：`流年(2024)` 返回从 2024 甲辰起的 10 柱。
 */
export function 流年(今年公历年: number): 流年柱[] {
  const 柱: 流年柱[] = [];
  for (let i = 0; i < 流年柱数; i++) {
    const 年 = 今年公历年 + i;
    const 序号 = (((年 - 4) % 60) + 60) % 60;
    柱.push({ 年, 干支: liushijiazi(序号) });
  }
  return 柱;
}
