import { describe, it, expect } from "vitest";
import { 经度修正分钟数, 应用经度修正, 参考经度, 每度分钟数 } from "../src/solar-time.js";

describe("经度修正 - 偏移量计算 (T5)", () => {
  // CONTEXT.md：经度修正 = (经度 − 120°) × 4 分钟/度
  it("常量：参考经度 120°、每度 4 分钟", () => {
    expect(参考经度).toBe(120);
    expect(每度分钟数).toBe(4);
  });

  it("中央经线 120° -> 偏移 0 分钟", () => {
    expect(经度修正分钟数(120)).toBe(0);
  });

  it("东偏 1°（121°）-> +4 分钟", () => {
    expect(经度修正分钟数(121)).toBe(4);
  });

  it("西偏 1°（119°）-> −4 分钟", () => {
    expect(经度修正分钟数(119)).toBe(-4);
  });

  // 成都约 104.08°E，真太阳时比钟表时晚约 63.7 分钟。
  it("成都 ~104.08° -> 约 −63.7 分钟", () => {
    const m = 经度修正分钟数(104.081534);
    expect(m).toBeCloseTo(-63.673864, 4);
  });

  // 上海约 121.48°E，真太阳时比钟表时早约 5.9 分钟（即 +5.9）。
  it("上海 ~121.48° -> 约 +5.9 分钟", () => {
    const m = 经度修正分钟数(121.480539);
    expect(m).toBeCloseTo(5.922156, 4);
  });
});

describe("经度修正 - 时间戳平移 (T5)", () => {
  // 2000-01-01 12:00 钟表时（北京时间）= UTC 2000-01-01 04:00
  const base = Date.UTC(2000, 0, 1, 4, 0);

  it("120° 中央经线 -> 时间戳不变", () => {
    expect(应用经度修正(base, 120)).toBe(base);
  });

  it("121° -> 时间戳 +4 分钟（240_000 ms）", () => {
    expect(应用经度修正(base, 121)).toBe(base + 4 * 60_000);
  });

  it("116° -> 时间戳 −16 分钟", () => {
    expect(应用经度修正(base, 116)).toBe(base - 16 * 60_000);
  });

  it("104° -> 时间戳 −64 分钟", () => {
    expect(应用经度修正(base, 104)).toBe(base - 64 * 60_000);
  });
});
