import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  deriveBookBuild,
  findGeneratedAdapterDrift,
  renderGeneratedAdapters,
} from "./book-build-module.mjs";
import { bookBuildStrategies } from "./book-build-strategies.mjs";

const generatedMarker = "// Generated by scripts/generate-book-adapters.mjs. Do not edit.";

function readJson(file) {
  return JSON.parse(readFileSync(file, "utf8"));
}

function walkFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const file = path.join(directory, entry.name);
    return entry.isDirectory() ? walkFiles(file) : [file];
  });
}

export function readBookBuildInputs(root) {
  const catalogs = [];
  for (const bookId of Object.keys(bookBuildStrategies)) {
    const catalogPath = path.join(root, "src/books", bookId, "catalog.json");
    const auditPath = path.join(root, "content/books", bookId, "audit.json");
    if (!existsSync(catalogPath)) throw new Error(`${bookId}：缺少 catalog.json`);
    if (!existsSync(auditPath)) throw new Error(`${bookId}：缺少 audit.json`);
    const catalog = readJson(catalogPath);
    if (catalog.book.id !== bookId) {
      throw new Error(`${bookId}：catalog book.id 为 ${catalog.book.id}`);
    }
    const chaptersDirectory = path.join(root, "content/books", bookId, "chapters");
    const chapterFiles = walkFiles(chaptersDirectory)
      .filter((file) => file.endsWith(".md"));
    const expectedChapterPaths = new Set(
      catalog.volumes.flatMap((volume) =>
        volume.chapters.map((chapter) => `${volume.id}/${chapter.id}.md`)
      ),
    );
    const actualChapterPaths = new Set(
      chapterFiles.map((file) =>
        path.relative(chaptersDirectory, file).split(path.sep).join("/")
      ),
    );
    for (const expectedPath of expectedChapterPaths) {
      if (!actualChapterPaths.has(expectedPath)) {
        throw new Error(`${bookId}：缺失正文文件 ${expectedPath}`);
      }
    }
    for (const actualPath of actualChapterPaths) {
      if (!expectedChapterPaths.has(actualPath)) {
        throw new Error(`${bookId}：正文文件不在 catalog ${actualPath}`);
      }
    }
    const chapterContents = Object.fromEntries(
      chapterFiles.map((file) => [
        path.basename(file, ".md"),
        readFileSync(file, "utf8"),
      ]),
    );
    deriveBookBuild({
      catalog,
      audit: readJson(auditPath),
      chapterContents,
    });
    catalogs.push(catalog);
  }

  const catalogBookIds = readdirSync(path.join(root, "src/books"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .filter((entry) => existsSync(path.join(root, "src/books", entry.name, "catalog.json")))
    .map((entry) => entry.name);
  for (const bookId of catalogBookIds) {
    if (!(bookId in bookBuildStrategies)) {
      throw new Error(`${bookId}：缺少构建策略`);
    }
  }
  return catalogs;
}

function withMarker(output) {
  return Object.fromEntries(
    Object.entries(output).map(([file, source]) => [file, `${generatedMarker}\n${source}`]),
  );
}

function readGeneratedAdapters(root) {
  const candidates = [
    path.join(root, "src/books/registry.ts"),
    ...walkFiles(path.join(root, "src/books")).filter((file) => file.endsWith(".ts")),
  ];
  return Object.fromEntries(
    [...new Set(candidates)]
      .filter((file) => existsSync(file))
      .filter((file) => readFileSync(file, "utf8").startsWith(generatedMarker))
      .map((file) => [path.relative(root, file), readFileSync(file, "utf8")]),
  );
}

export function generateBookAdapters(root, { check = false } = {}) {
  const expected = withMarker(renderGeneratedAdapters(readBookBuildInputs(root)));
  const actual = readGeneratedAdapters(root);
  const drift = findGeneratedAdapterDrift(expected, actual);
  if (check) {
    if (drift.length > 0) {
      throw new Error(
        `generated 典籍 adapter 已陈旧：\n${drift.join("\n")}\n请运行 npm run generate:book-adapters`,
      );
    }
    return { changed: false, files: Object.keys(expected) };
  }

  for (const file of Object.keys(actual)) {
    if (!(file in expected)) unlinkSync(path.join(root, file));
  }
  for (const [file, source] of Object.entries(expected)) {
    const target = path.join(root, file);
    mkdirSync(path.dirname(target), { recursive: true });
    if (!existsSync(target) || readFileSync(target, "utf8") !== source) {
      writeFileSync(target, source);
    }
  }
  return { changed: drift.length > 0, files: Object.keys(expected) };
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) {
  const root = process.cwd();
  const check = process.argv.includes("--check");
  const result = generateBookAdapters(root, { check });
  console.log(
    check
      ? `generated 典籍 adapter 检查通过：${result.files.length} 个文件`
      : `generated 典籍 adapter 已生成：${result.files.length} 个文件`,
  );
}
