#!/usr/bin/env node
// 生成 src/data/cities.generated.ts：省 -> 地级市 -> 经度（数值）。
//
// 数据源：
//   - 行政区划（省/地级市结构）取自 modood/Administrative-divisions-of-China
//     (WTFPL，允许任意使用)，仓库 https://github.com/modood/Administrative-divisions-of-China
//     的 dist/provinces.json + dist/cities.json。
//   - 地级市经度取自 88250/city-geo (MulanPSL-2.0，宽松许可) 的 data.json
//     中 area==="" 的条目（每地级市一条）。
//
// 排盘只需经度（经度修正公式 真太阳时 = 钟表时 + (经度 − 120°) × 4 分钟/度），
// 故本数据只保留经度，体积小、意图清晰。运行：
//   node scripts/build-cities-data.cjs > src/data/cities.generated.ts
//
// 源数据文件需预先放置于 ./data-src/ 下（provinces.json / cities.json / city-geo-data.json）。

"use strict";

const fs = require("node:fs");
const path = require("node:path");

const SRC_DIR = path.join(__dirname, "data-src");
const OUT = process.argv[2] || null;

const provinces = JSON.parse(
  fs.readFileSync(path.join(SRC_DIR, "provinces.json"), "utf8"),
);
const cities = JSON.parse(
  fs.readFileSync(path.join(SRC_DIR, "cities.json"), "utf8"),
);
const geoEntries = JSON.parse(
  fs.readFileSync(path.join(SRC_DIR, "city-geo-data.json"), "utf8"),
);

const provCode2Name = new Map();
for (const p of provinces) provCode2Name.set(p.code, p.name);

// 经度查找：以 省|市 为键，取 area==="" 的条目。
const geo = new Map();
for (const e of geoEntries) {
  if (e.area !== "") continue;
  geo.set(`${e.province}|${e.city}`, Number(e.lng));
}

// 按 modood 顺序构建 省 -> { 市 -> 经度 }。
// 排除 "省直辖县级行政区划" / "自治区直辖县级行政区划" 等 GB/T 2260 占位桶：
// 它们是散布的县级行政单位集合（济源、天门/仙桃/潜江、石河子/阿拉尔……），
// 单一经度无意义，且 city-geo 对部分占位桶无坐标。
const PSEUDO_CITY = /直辖县级行政区划$/;
const out = {};
const skipped = new Set();
const missing = [];
for (const c of cities) {
  if (PSEUDO_CITY.test(c.name)) {
    skipped.add(c.name);
    continue;
  }
  const provName = provCode2Name.get(c.provinceCode);
  if (!provName) {
    missing.push(`${c.provinceCode}/${c.name}（未知省份）`);
    continue;
  }
  const lng = geo.get(`${provName}|${c.name}`);
  if (lng === undefined || Number.isNaN(lng) || lng === 0) {
    missing.push(`${provName}/${c.name}`);
    continue;
  }
  (out[provName] ||= {})[c.name] = Number(lng.toFixed(6));
}

if (missing.length) {
  console.error(`错误：缺少 ${missing.length} 个城市经度，已中止：`);
  console.error(missing.slice(0, 50).join("\n"));
  process.exit(1);
}

const provCount = Object.keys(out).length;
const cityCount = Object.values(out).reduce((s, m) => s + Object.keys(m).length, 0);

// city-geo 部分占位桶坐标缺失或为 0，列出被跳过的桶名便于核对。
const lines = [];
lines.push("// AUTO-GENERATED by scripts/build-cities-data.cjs — 请勿手工编辑。");
lines.push("// 数据源：modood/Administrative-divisions-of-China (WTFPL) + 88250/city-geo (MulanPSL-2.0)。");
lines.push(`// 共 ${provCount} 省、${cityCount} 地级市（排除直辖县级占位桶）。每市给出经度（度，东经为正）。`);
if (skipped.size) lines.push(`// 占位桶已跳过：${Array.from(skipped).join("、")}。`);
lines.push("// 真太阳时 = 钟表时 + (经度 − 120°) × 4 分钟/度（见 CONTEXT.md 经度修正）。");
lines.push("");
lines.push("/** 省 -> 地级市 -> 经度（度，东经为正）。生成自 city-geo，仅含中国大陆省/地级市。 */");
lines.push("export const CITIES: Readonly<Record<string, Readonly<Record<string, number>>>> =");
lines.push(JSON.stringify(out, null, 2) + ";");
lines.push("");

const text = lines.join("\n");

if (OUT) {
  fs.writeFileSync(OUT, text);
  console.error(`已生成 ${OUT}（${provCount} 省、${cityCount} 市）`);
} else {
  process.stdout.write(text);
}